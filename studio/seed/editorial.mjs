export function textsToCheck() {
  const lines = [];
  const visit = (value) => {
    if (typeof value === "string") lines.push(value);
    else if (Array.isArray(value)) value.forEach(visit);
    else if (value && typeof value === "object") {
      if (value._type === "span" && value.text) lines.push(value.text);
      else Object.values(value).forEach(visit);
    }
  };
  visit(seriesDocs);
  visit(workDocs);
  visit(settingsDoc);
  return lines.filter((line) => line.length > 40);
}
